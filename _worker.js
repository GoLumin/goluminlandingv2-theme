export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const path = url.pathname.replace(/\/+$/, "") || "/";

    const target = REDIRECTS[path];
    if (target) return Response.redirect(new URL(target, url.origin).toString(), 301);

    if (url.pathname.startsWith("/api/")) {
      const upstream = new Request(CMS_ORIGIN + url.pathname + url.search, request);
      return fetch(upstream);
    }

    // Client proposals and their contracts are generated by the Astro site and
    // were never carried over here. They stopped resolving the moment this
    // domain left that origin, which broke every proposal link already sent to
    // a client. Pass them straight through rather than move the content.
    if (url.pathname === "/proposals" || url.pathname.startsWith("/proposals/")) {
      const upstream = new Request(PROPOSALS_ORIGIN + url.pathname + url.search, request);
      return fetch(upstream);
    }

    return env.ASSETS.fetch(request);
  },
};
